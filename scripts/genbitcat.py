#!/usr/bin/env python3
"""Generate desktop/bitcat.h -- the system mark, from BitCat.png at the
tree root.

The mark is stored the way the desktop's icons are: an 8bpp indexed
sprite, one byte per pixel into a palette of six colours, 32x32.  The
disc, its rim and the cat's ink are baked into the sprite, so drawing it
is a palette lookup and a solid store per opaque pixel -- no per-pixel
blending anywhere, which is what an About banner painted every frame
wants.  The source's antialiased edges are quantized into the two grey
shades the palette carries.

Usage: python3 scripts/genbitcat.py   (writes desktop/bitcat.h)
"""

import os
import sys

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit("genbitcat.py needs Pillow: python3 -m pip install pillow")

OUT = 32

# 0 = transparent; the rest are the sprite's own colours, RGB.
PALETTE = [
    (0, 0, 0),          # 0: transparent
    (255, 255, 255),    # 1: the disc
    (74, 148, 226),     # 2: the rim
    (24, 24, 28),       # 3: ink, full
    (110, 110, 118),    # 4: ink, half
    (200, 200, 206),    # 5: ink, faint
]

INK_SIDE = 26  # the cat's box inside the 32x32 disc
INK_X = (OUT - INK_SIDE) // 2


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = os.path.join(here, "BitCat.png")

    # the cat: downscaled luminance, so ink coverage = 255 - luminance
    gray = Image.open(src).convert("L").resize((INK_SIDE, INK_SIDE), Image.LANCZOS)
    g = gray.tobytes()

    # the disc: rounded rectangle, 1px rim, the rest white
    mask = Image.new("L", (OUT, OUT), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, OUT - 1, OUT - 1), radius=9, fill=255)
    rim = Image.new("L", (OUT, OUT), 0)
    ImageDraw.Draw(rim).rounded_rectangle((0, 0, OUT - 1, OUT - 1), radius=9, outline=255)
    m, rm = mask.tobytes(), rim.tobytes()

    px = bytearray(OUT * OUT)
    for i in range(OUT * OUT):
        if rm[i]:
            px[i] = 2  # rim
        elif m[i]:
            px[i] = 1  # disc
    # the cat over the disc, quantized into the palette's ink shades
    for j in range(INK_SIDE):
        for i in range(INK_SIDE):
            cov = 255 - g[j * INK_SIDE + i]
            if cov > 160:
                v = 3
            elif cov > 70:
                v = 4
            elif cov > 24:
                v = 5
            else:
                continue
            px[(INK_X + j) * OUT + INK_X + i] = v

    out = []
    out.append("/* The system mark -- GENERATED by scripts/genbitcat.py from")
    out.append(" * BitCat.png, do not edit by hand.  %dx%d, 8bpp indexed:" % (OUT, OUT))
    out.append(" * one byte per pixel into the palette below, 0 = transparent.")
    out.append(" * Disc, rim and ink are baked in; drawing is a lookup and a")
    out.append(" * solid store per opaque pixel. */")
    out.append("#pragma once")
    out.append("")
    out.append("#define BITCAT_W %d" % OUT)
    out.append("#define BITCAT_H %d" % OUT)
    out.append("#define BITCAT_PAL %d" % len(PALETTE))
    out.append("")
    out.append("/* RGB, one entry per palette index */")
    out.append("static const unsigned int bitcat_pal[BITCAT_PAL] = {")
    for c in PALETTE:
        out.append("    0x%02X%02X%02Xu," % c)
    out.append("};")
    out.append("")
    out.append("static const unsigned char bitcat_px[BITCAT_W * BITCAT_H] = {")
    for r in range(OUT):
        row = ", ".join(str(px[r * OUT + c]) for c in range(OUT))
        out.append("    %s," % row)
    out.append("};")

    dest = os.path.join(here, "desktop", "bitcat.h")
    with open(dest, "w") as f:
        f.write("\n".join(out))
    print("wrote %s" % dest, file=sys.stderr)


if __name__ == "__main__":
    main()
