/* ---- input, desktop-side (loop.c translates; port.c + loop.c) ----
 * The kernel's unified input queue speaks decoded characters and relative
 * mouse deltas; the desktop speaks its own two vocabularies, both defined
 * here so every module shares them.  loop.c turns the queue's events into
 * mouse callback arguments (absolute position, tracked from the deltas)
 * and into dsk_events for the keyboard.
 *
 * What this kernel's queue cannot say: there are no key-up events, no
 * scancodes and no Ctrl -- extended (E0) keys never reach it, so the
 * arrow/Home/End/PageUp/Delete codes below are defined for the modules'
 * switch statements but only the wheel-driven UP/DOWN ever fire.  Shift
 * is visible as the key's INPUT_MOD_SHIFT flag, which is how Paint's
 * straight-line constraint still works. */
#define LNXRM_MB_LEFT   1
#define LNXRM_MB_MIDDLE 2
#define LNXRM_MB_RIGHT  4

#define LNXRM_EV_KEY_DOWN 1 /* the only event wm_key receives       */
#define LNXRM_EV_KEY_UP   2 /* not produced by this kernel's queue  */
#define LNXRM_EV_MOUSE    3 /* mouse moves through callbacks, not this */

#define LNXRM_KEY_BACKSPACE '\b'
#define LNXRM_KEY_TAB       '\t'
#define LNXRM_KEY_ENTER     '\n'
#define LNXRM_KEY_ESC       27
#define LNXRM_KEY_SPACE     ' '
#define LNXRM_KEY_DELETE    128
#define LNXRM_KEY_UP        129
#define LNXRM_KEY_DOWN      130
#define LNXRM_KEY_LEFT      131
#define LNXRM_KEY_RIGHT     132
#define LNXRM_KEY_PGUP      133
#define LNXRM_KEY_PGDN      134
#define LNXRM_KEY_HOME      135
#define LNXRM_KEY_END       136

struct dsk_event {
    int type; /* LNXRM_EV_KEY_DOWN                                       */
    int code; /* LNXRM_KEY_* -- the printable ones are the character     */
    int ch;   /* the decoded character, for handlers that want raw text  */
};

/* ---- applications ---- */
struct win;

struct app {
    const char *name;  /* Start menu entry and taskbar button label */
    const char *title; /* initial title bar text                   */
    int w, h;          /* default *outer* window size              */
    void (*open)(struct win *w);  /* allocate w->state              */
    void (*paint)(struct win *w); /* client area, clip already set  */
    /* All four callbacks get client-relative coordinates; `btn` is a
     * LNXRM_MB_* mask with exactly one bit for down/up, and `clicks` is
     * 1 for a single click, 2 for a double-click on the same spot. */
    void (*down)(struct win *w, int x, int y, int btn, int clicks);
    void (*drag)(struct win *w, int x, int y, int dx, int dy);
    void (*up)(struct win *w, int x, int y, int btn);
    void (*key)(struct win *w, const struct dsk_event *ev);
    void (*close)(struct win *w); /* free w->state */
    /* Called once per frame for every open window, whether or not it is
     * visible.  A window with a clock or a counter needs something to
     * wake it up -- nothing else repaints a window nobody has touched --
     * so it dirties itself from here when the value it displays changes. */
    void (*tick)(struct win *w);
};

