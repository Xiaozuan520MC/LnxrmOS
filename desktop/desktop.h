/* LnxrmOS desktop -- the Win98-flavoured shell, entirely in user space.
 *
 * One process, one thread, no IPC: the window manager, the taskbar and
 * every application are modules of this binary, which draws into a private
 * backbuffer and hands finished rectangles to the kernel framebuffer
 * through fb_blit.  The header is the contract between those modules --
 * the palette and the 3-D bevel vocabulary that make a rectangle look
 * like Windows, the window geometry, and the application vtable.
 *
 * Coordinate system: one screen, pixels, y down.  A window's x/y/w/h is
 * the *outer* rectangle (everything the mouse can grab); the client area
 * a module draws into is derived from it by win_cx()/win_cy()/... so the
 * bevel and title-bar thicknesses live in one place only.
 */
#pragma once
#include "ulib.h"

/* ---- palette: the Win98 bevel vocabulary in a light, modern dress ----
 * Every module still speaks in raised edges and sunken fields, because
 * that is how a rectangle stops looking like a rectangle -- but the
 * faces are now the near-white of a current window, the dark edge is
 * soft instead of half-grey, and the teal desktop survives as a ramp
 * that stays close enough to the old colour to stay recognisable. */
#define RGB(r, g, b) (((u32)(r) << 16) | ((u32)(g) << 8) | (u32)(b))

