/* ---- modifier keys (loop.c) ----
 * Shift is tracked from the key events' INPUT_MOD_SHIFT flag: the driver
 * says which modifiers made a character, and the last key to arrive wins.
 * This is how Paint knows a drag has to come out straight.  There is no
 * Ctrl anywhere in this kernel's input queue -- the keyboard driver never
 * produces it -- so desktop_ctrl() is always 0, and Notepad's save is the
 * Save button. */
